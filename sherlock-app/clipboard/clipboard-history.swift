import AppKit

public struct ClipboardEntry: Codable, Sendable {
  public let text: String
  public let date: Date
  public let sourceAppPath: String?
}

public final class ClipboardHistory {
  public private(set) var entries: [ClipboardEntry] = []
  private var retention: TimeInterval = 7 * 24 * 60 * 60
  private var changeCount = -1
  private var timer: Timer?

  public init() {
    entries = (try? Data(contentsOf: historyURL)).flatMap {
      try? JSONDecoder().decode([ClipboardEntry].self, from: $0)
    } ?? []
  }

  public func configure(enabled: Bool, retentionDays: Int) {
    retention = TimeInterval(retentionDays) * 24 * 60 * 60
    if enabled, timer == nil {
      changeCount = -1
      let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
        MainActor.assumeIsolated { self?.poll() }
      }
      RunLoop.main.add(timer, forMode: .common)
      self.timer = timer
    } else if !enabled {
      timer?.invalidate()
      timer = nil
    }
    prune()
  }

  public func clear() {
    entries = []
    save()
  }

  private func poll() {
    let pasteboard = NSPasteboard.general
    guard pasteboard.changeCount != changeCount else { return }
    changeCount = pasteboard.changeCount
    let types = Set(pasteboard.types ?? [])
    guard types.isDisjoint(with: ignoredTypes), let text = pasteboard.string(forType: .string),
      !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
    else { return }
    entries.removeAll { $0.text == text }
    entries.insert(
      ClipboardEntry(
        text: text, date: Date(),
        sourceAppPath: NSWorkspace.shared.frontmostApplication?.bundleURL?.path),
      at: 0)
    prune()
  }

  private func prune() {
    let cutoff = Date().addingTimeInterval(-retention)
    entries = Array(entries.prefix { $0.date > cutoff }.prefix(maxEntries))
    save()
  }

  private func save() {
    try? FileManager.default.createDirectory(
      at: historyURL.deletingLastPathComponent(), withIntermediateDirectories: true)
    try? JSONEncoder().encode(entries).write(to: historyURL, options: [.atomic])
    try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: historyURL.path)
  }
}

private let historyURL = URL.applicationSupportDirectory.appending(path: "Sherlock/clipboard.json")

private let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
  transientType, concealedType, NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
  NSPasteboard.PasteboardType("com.agilebits.onepassword"),
  NSPasteboard.PasteboardType("de.petermaurer.TransientPasteboardType"),
]

let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")

private let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")

private let maxEntries = 500
